// Builds src/styles/tokens.css from design/tokens.json. No dependencies: run with `pnpm tokens`.
// Primitives become --p-<ramp>-<step>. Semantic tokens become --<name> and are written once per theme. Component tokens
// become --k-<name> and point at semantic tokens, so they follow the theme without being written twice.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));

const primitive = (reference) => {
  const [ramp, step] = reference.split(".");
  if (!tokens.primitives[ramp]?.[step]) throw new Error(`unknown primitive ${reference}`);
  return `var(--p-${ramp}-${step})`;
};

const lines = [];
const add = (text = "") => lines.push(text);

add("/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */");
add(":root {");
for (const [ramp, steps] of Object.entries(tokens.primitives)) {
  for (const [step, value] of Object.entries(steps)) add(`  --p-${ramp}-${step}: ${value};`);
}
for (const [name, value] of Object.entries(tokens.scale)) add(`  --${name}: ${value};`);
add("}");
add("");

const semanticBlock = (theme, indent = "  ") => {
  const out = [];
  for (const [name, reference] of Object.entries(tokens.semantic[theme])) {
    out.push(`${indent}--${name}: ${primitive(reference)};`);
  }
  return out;
};

const semanticNames = Object.keys(tokens.semantic.light);
for (const name of Object.keys(tokens.semantic.dark)) {
  if (!semanticNames.includes(name)) throw new Error(`dark theme has ${name} but light does not`);
}
for (const name of semanticNames) {
  if (!(name in tokens.semantic.dark)) throw new Error(`light theme has ${name} but dark does not`);
}

add(":root {");
add("  color-scheme: light;");
lines.push(...semanticBlock("light"));
add("}");
add("");
add("@media (prefers-color-scheme: dark) {");
add('  :root:not([data-theme="light"]) {');
add("    color-scheme: dark;");
lines.push(...semanticBlock("dark", "    "));
add("  }");
add("}");
add("");
add(':root[data-theme="light"] {');
add("  color-scheme: light;");
lines.push(...semanticBlock("light"));
add("}");
add("");
add(':root[data-theme="dark"] {');
add("  color-scheme: dark;");
lines.push(...semanticBlock("dark"));
add("}");
add("");

add(":root {");
for (const [name, reference] of Object.entries(tokens.component)) {
  if (!semanticNames.includes(reference)) throw new Error(`component ${name} points at unknown ${reference}`);
  add(`  --k-${name}: var(--${reference});`);
}
add("}");

const target = join(root, "src/styles/tokens.css");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, lines.join("\n") + "\n");
console.log(`tokens: wrote ${target}`);
